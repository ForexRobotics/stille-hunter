"""Compatibility and contract tests for the stable public API (docs/stability.md).

1. Ledgers written by every earlier release still load and work. The files in
   tests/compat/ledgers/<version>/ were generated by that release's own code
   (secret-looking marker values replaced with "REDACTED-..." so they are not
   mistaken for real secrets). Add a folder for each new release.
2. The plugin contracts and the JSON shapes consumers rely on keep their
   names. A failure here means a breaking change: it needs a major version.
"""
import inspect
import shutil
import sys
from pathlib import Path

import pytest

from stille_hunter import check, generate, history, ledger, report
from stille_hunter.check import Canary, CheckSource, Hit, load_ledger

LEDGERS = Path(__file__).parent / "compat" / "ledgers"
FIXTURES = sorted(p for p in LEDGERS.glob("*/*") if p.suffix in (".jsonl", ".csv"))

#: marker kinds each type has written since its first release
EXPECTED_MARKERS = {
    "member": {"email", "user_id", "password_hash", "record_id"},
    "db_dump": {"email", "marker", "record_id"},
    "aws_key": {"aws_access_key_id", "aws_secret_access_key", "record_id"},
    "api_token": {"api_token", "record_id"},
    "azure_credential": {"azure_client_id", "azure_client_secret", "record_id"},
    "mcp_config": {"mcp_token", "record_id"},
    "kubeconfig": {"kube_token", "record_id"},
}
#: fields that are context or bookkeeping, never markers
CONTEXT = {"type", "table", "retired_at", "retired_reason", "created_at", "seed_tag",
           "detect", "locale"}


def test_every_released_version_has_fixtures():
    # 0.5.0 is skipped: yanked, and its code is identical to 0.4.0
    assert {p.name for p in LEDGERS.iterdir()} >= {"v0.1.0", "v0.2.0", "v0.3.0", "v0.4.0",
                                                   "v0.5.1", "v0.6.0"}
    assert len(FIXTURES) >= 25


@pytest.mark.parametrize("path", FIXTURES, ids=lambda p: f"{p.parent.name}/{p.name}")
def test_old_ledger_loads_with_all_markers(path):
    rows = ledger.read_rows(str(path))
    canaries = load_ledger(str(path), include_inbox=True)
    assert len(canaries) == len(rows) == 3
    kind = path.stem
    for c, row in zip(canaries, rows, strict=True):
        assert c.record_id == row["record_id"] and c.seed_tag == row["seed_tag"]
        assert EXPECTED_MARKERS[kind] <= set(c.tokens()), (kind, set(c.tokens()))
        assert not (CONTEXT & set(c.tokens()))
        assert ledger.row_type(row) == kind               # type inferred for old rows
    # search-only by default: inbox canaries are left to `inbox`
    searchable = load_ledger(str(path), include_inbox=False)
    assert len(searchable) == sum(r.get("detect", "search") != "inbox" for r in rows)


def test_old_member_ledgers_work_with_inbox_matching():
    from stille_hunter import inbox
    for path in sorted(LEDGERS.glob("*/member.jsonl")):
        canaries = load_ledger(str(path), include_inbox=True)
        boxed = [c for c in canaries if c.detect == "inbox"]
        if not boxed:
            continue
        m = inbox.Matcher(canaries)
        assert m.match(boxed[0].email.upper()).record_id == boxed[0].record_id


@pytest.mark.parametrize("version", ["v0.1.0", "v0.4.0"])
def test_old_ledgers_can_be_listed_retired_and_rotated(tmp_path, version):
    path = tmp_path / "old.ledger.jsonl"
    shutil.copy(LEDGERS / version / "member.jsonl", path)
    rows = ledger.read_rows(str(path))
    assert ledger.summary(rows)[0]["active"] == 3
    plan = ledger.rotation_plan(rows, f"compat-{version}", [])
    assert plan[:4] == ["--type", "member", "--count", "3"]
    res = ledger.rotate(str(path), f"compat-{version}", str(tmp_path / "new"), [])
    assert res["retired"] == 3 and res["added"] == 3
    assert len(load_ledger(str(path), include_inbox=True)) == 3   # only the new batch


# ---- the plugin contracts ---------------------------------------------------
def _params(fn):
    return list(inspect.signature(fn).parameters)


def test_check_source_contract():
    assert _params(CheckSource.__init__) == ["self", "config"]
    src = CheckSource(api_key="k")
    assert src.config == {"api_key": "k"} and src.stats == {}
    src.progress(1, 2, "note")                               # callable, no-op by default
    assert src.available() == (True, "")
    assert _params(CheckSource.check) == ["self", "canaries"]
    assert {"name", "supports"} <= set(vars(CheckSource))
    assert _params(check.register) == ["cls"]
    assert _params(check.run_check)[:3] == ["canaries", "source_names", "source_config"]


def test_canary_and_hit_shapes():
    fields = [f for f in Canary.__dataclass_fields__]
    assert fields == ["record_id", "seed_tag", "detect", "locale", "email", "user_id",
                      "password_hash", "extra"]
    c = Canary("abc123", "t", "search", "jp", "a@b.c", "u", "h", {"marker": "M"})
    assert set(c.tokens()) == {"email", "user_id", "password_hash", "record_id", "marker"}
    h = Hit(canary=c, source="s", token_kind="email", token="a@b.c", location="here")
    assert list(h.to_dict()) == ["record_id", "seed_tag", "locale", "source", "token_kind",
                                 "token", "location", "detail", "found_at"]


def test_canary_type_contract():
    assert _params(generate.CanaryType.add_arguments) == ["self", "parser"]
    assert _params(generate.CanaryType.generate) == ["self", "args", "count"]
    assert {"name", "description"} <= set(vars(generate.CanaryType))
    assert _params(generate.register_type) == ["cls"]
    assert len(generate.new_token()) == 6
    rec = {"record_id": "abc123", "x": 1, "_detect": "inbox", "_ledger": {"email": "e"}}
    row = generate._ledger_row(rec, "tag", None, "member")
    assert list(row)[:3] == ["record_id", "seed_tag", "detect"]
    assert row["email"] == "e" and row["type"] == "member" and "created_at" in row


def test_report_and_history_json_shapes():
    from datetime import datetime, timezone
    now = datetime.now(timezone.utc)
    rep = report.build(canaries=[], source_names=["null"], hits=[], results=[],
                       started=now, finished=now)
    assert {"tool", "version", "title", "started_at", "finished_at", "duration_seconds",
            "ledgers", "summary", "canaries", "sources", "hits"} <= set(rep)
    line = history.entry(rep)
    assert history.SCHEMA == 1
    assert set(line) == {"schema", "started_at", "finished_at", "version", "ledgers",
                         "canaries", "sources", "hits"}


# ---- third-party plugins via entry points ------------------------------------
def test_entry_point_plugins_are_loaded(tmp_path, monkeypatch):
    from importlib import metadata

    from stille_hunter import _plugins
    (tmp_path / "thirdparty_src.py").write_text(
        "from stille_hunter.check import CheckSource, register\n"
        "@register\n"
        "class ThirdParty(CheckSource):\n"
        "    name = 'thirdparty_demo'\n"
        "    def check(self, canaries):\n"
        "        return []\n", encoding="utf-8")
    (tmp_path / "broken_src.py").write_text("raise RuntimeError('boom')\n", encoding="utf-8")
    monkeypatch.syspath_prepend(str(tmp_path))
    eps = [metadata.EntryPoint("demo", "thirdparty_src", _plugins.SOURCE_GROUP),
           metadata.EntryPoint("broken", "broken_src", _plugins.SOURCE_GROUP)]
    monkeypatch.setattr(metadata, "entry_points",
                        lambda group=None: [e for e in eps if e.group == group])
    try:
        problems = check.load_plugins()
        assert "thirdparty_demo" in check._REGISTRY
        assert any("broken" in p and "boom" in p for p in problems)
    finally:
        check._REGISTRY.pop("thirdparty_demo", None)
        sys.modules.pop("thirdparty_src", None)
        sys.modules.pop("broken_src", None)


def test_fixture_files_carry_no_real_looking_secrets():
    secret_fields = {"aws_access_key_id", "aws_secret_access_key", "api_token",
                     "azure_client_secret", "mcp_token", "kube_token"}
    for path in FIXTURES:
        for row in ledger.read_rows(str(path)):
            for k in secret_fields & set(row):
                assert row[k].startswith("REDACTED-"), (path, k)


def test_fixture_tool_writes_loadable_redacted_ledgers(tmp_path, monkeypatch):
    import importlib.util

    import stille_hunter
    spec = importlib.util.spec_from_file_location(
        "compat_fixtures", Path(__file__).parents[1] / "tools" / "compat_fixtures.py")
    tool = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tool)
    monkeypatch.setattr(stille_hunter, "__version__", "9.9.9")
    monkeypatch.chdir(tmp_path)
    assert tool.main() == 0
    out = tmp_path / "tests" / "compat" / "ledgers" / "v9.9.9"
    files = sorted(p.name for p in out.iterdir())
    assert "member.csv" in files and "kubeconfig.jsonl" in files
    for p in out.iterdir():
        rows = ledger.read_rows(str(p))
        assert len(load_ledger(str(p), include_inbox=True)) == len(rows) == 3
        for r in rows:
            assert r["type"] == p.stem
            for k in {"api_token", "aws_secret_access_key", "kube_token"} & set(r):
                assert r[k].startswith("REDACTED-")
    assert tool.main() == 2                                  # never overwrites
